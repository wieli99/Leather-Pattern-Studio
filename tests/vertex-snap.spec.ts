import { test, expect } from "@playwright/test";
import { manualScreenshot } from "./manual-capture";

test("Shift constrains vertex dragging and supports undo/redo", { tag: "@manual" }, async ({ page }) => {
  await page.goto("/");
  const polyline = page.getByRole("button", { name: "Polyline (P)", exact: true });
  await expect(polyline).toBeEnabled();
  await page.getByRole("checkbox", { name: "Grid snap", exact: true }).uncheck();
  await page.getByRole("checkbox", { name: "Object snap", exact: true }).uncheck();
  await polyline.click();
  const canvas = page.getByLabel("Pattern drawing canvas");
  await canvas.click({ position: { x: 240, y: 240 } });
  await canvas.click({ position: { x: 500, y: 350 } });
  await canvas.click({ position: { x: 600, y: 240 } });
  await page.keyboard.press("Enter");
  await page.getByRole("button", { name: "Select (V)", exact: true }).click();
  await page.getByText("Vertex coordinates", { exact: true }).click();
  const y = page.getByLabel("Vertex 1 Y", { exact: true });
  const x = page.getByLabel("Vertex 1 X", { exact: true });
  const initialX = await x.inputValue(), initialY = await y.inputValue();
  const box = (await canvas.boundingBox())!;
  await page.mouse.move(box.x + 240, box.y + 240);
  await page.mouse.down();
  await page.mouse.move(box.x + 320, box.y + 250);
  await page.keyboard.down("Shift");
  await expect(page.locator("aside .inspector-hint")).toContainText("Constrain movement to 45°");
  await page.locator("aside .inspector-hint").getByText("Constrain movement to 45°").scrollIntoViewIfNeeded();
  await manualScreenshot(page, "vertex-snap.png");
  await page.mouse.up();
  await page.keyboard.up("Shift");
  await expect(y).toHaveValue(initialY);
  await expect(x).not.toHaveValue(initialX);
  const movedX = await x.inputValue();
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await expect(x).toHaveValue(initialX);
  await page.getByRole("button", { name: "Redo", exact: true }).click();
  await expect(x).toHaveValue(movedX);
  await expect(y).toHaveValue(initialY);
});
